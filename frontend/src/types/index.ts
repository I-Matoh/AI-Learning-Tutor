/**
 * Type guard to check if an object is a valid Course.
 * 
 * @param value - Unknown value to check
 * @returns True if the value is a valid Course object
 * 
 * @security This only validates structure, not content.
 * For security, also validate data from external sources.
 * 
 * @example
 * const parsed = JSON.parse(localStorage.getItem('course'));
 * if (isValidCourse(parsed)) {
 *   // TypeScript now knows parsed is Course
 * }
 */
export function isValidCourse(value: unknown): value is Course {
  if (typeof value !== 'object' || value === null) return false;
  
  const course = value as Record<string, unknown>;
  
  return (
    typeof course.id === 'string' &&
    typeof course.title === 'string' &&
    typeof course.description === 'string' &&
    typeof course.createdAt === 'number' &&
    Array.isArray(course.modules)
  );
}

/**
 * Type guard to check if an object is a valid Quiz.
 */
export function isValidQuiz(value: unknown): value is Quiz {
  if (typeof value !== 'object' || value === null) return false;
  
  const quiz = value as Record<string, unknown>;
  
  return (
    typeof quiz.title === 'string' &&
    Array.isArray(quiz.questions)
  );
}
